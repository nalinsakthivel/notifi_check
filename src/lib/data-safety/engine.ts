import { DATA_GROUPS } from "@/lib/policy/types";
import { PURPOSES, type Purpose } from "./purposes";

export interface DataTypeAnswer {
  shared: boolean;
  optional: boolean;
  purposes: Purpose[];
}

export interface DataSafetyInput {
  /** Checked data-type ids (from DATA_GROUPS), each with its own per-type answer. */
  answers: Record<string, DataTypeAnswer>;
  /** Checked service ids (from SERVICES) — informational, listed alongside the table. */
  services: string[];
  encryptedInTransit: boolean;
  deletionSupported: boolean;
}

export function emptyDataSafetyInput(): DataSafetyInput {
  return {
    answers: {},
    services: [],
    encryptedInTransit: true,
    deletionSupported: false,
  };
}

export function emptyAnswer(): DataTypeAnswer {
  return { shared: false, optional: true, purposes: [] };
}

export interface DataSafetyRow {
  id: string;
  label: string;
  groupLabel: string;
  collected: true;
  shared: boolean;
  optional: boolean;
  purposes: Purpose[];
}

/** Builds the per-data-type worksheet rows, one per checked data type, in catalog order. */
export function buildDataSafetyRows(input: DataSafetyInput): DataSafetyRow[] {
  const rows: DataSafetyRow[] = [];
  for (const group of DATA_GROUPS) {
    for (const item of group.items) {
      const answer = input.answers[item.id];
      if (!answer) continue;
      rows.push({
        id: item.id,
        label: item.label,
        groupLabel: group.label,
        collected: true,
        shared: answer.shared,
        optional: answer.optional,
        purposes: answer.purposes,
      });
    }
  }
  return rows;
}

/** Plain-text worksheet, formatted for pasting straight into the Play Console form. */
export function toPlainText(input: DataSafetyInput): string {
  const rows = buildDataSafetyRows(input);
  const lines: string[] = [];

  lines.push("GOOGLE PLAY DATA SAFETY WORKSHEET");
  lines.push("Generated by Notifi Check — worksheet only, not submitted anywhere.");
  lines.push("");
  lines.push(`Data encrypted in transit: ${input.encryptedInTransit ? "Yes" : "No"}`);
  lines.push(`Users can request data deletion: ${input.deletionSupported ? "Yes" : "No"}`);
  lines.push("");

  if (rows.length === 0) {
    lines.push("No data types selected yet.");
  } else {
    let currentGroup = "";
    for (const row of rows) {
      if (row.groupLabel !== currentGroup) {
        currentGroup = row.groupLabel;
        lines.push(`-- ${currentGroup} --`);
      }
      lines.push(`${row.label}`);
      lines.push(`  Collected: Yes`);
      lines.push(`  Shared with third parties: ${row.shared ? "Yes" : "No"}`);
      lines.push(`  Collection is: ${row.optional ? "Optional" : "Required"}`);
      lines.push(
        `  Purpose(s): ${row.purposes.length > 0 ? row.purposes.join(", ") : "(none selected)"}`,
      );
      lines.push("");
    }
  }

  if (input.services.length > 0) {
    lines.push("-- SDKs / services in use (for your reference) --");
    lines.push(input.services.join(", "));
    lines.push("");
  }

  lines.push(
    "This worksheet is not legal advice and is not a substitute for Google's own Data Safety",
  );
  lines.push(
    "policy. You are responsible for the accuracy of what you submit in Play Console — Google",
  );
  lines.push("can suspend apps over Data Safety mismatches, so double-check every row.");

  return lines.join("\n");
}

export { PURPOSES };
export type { Purpose };
